# ── SQL 문장 모양 (항상) ──


def test_claim_sql_uses_skip_locked_and_orders():
    assert st.SQL_CLAIM_PENDING.endswith("limit %s for update skip locked")
    assert "where status = %s order by priority, id limit" in st.SQL_CLAIM_PENDING
    assert "order by id limit" in st.SQL_CLAIM_REMOVE and "order by priority" not in st.SQL_CLAIM_REMOVE
    assert st.SQL_CLAIM_PENDING.count("%s") == 2  # (status, limit)


def test_rank_sql_binds_array_and_joins_on_model():
    assert "any(%s::bigint[])" in st.SQL_RANK
    assert "1 - (g.embedding <=> m.embedding)" in st.SQL_RANK
    assert "m.member_id = %s and g.model = m.model" in st.SQL_RANK
    assert st.SQL_RANK.count("%s") == 2  # (memberId, grantIds)
    assert "grants " not in st.SQL_RANK and "member_grant_profiles" not in st.SQL_RANK  # 벡터 표만


def test_upsert_sql_casts_vector_and_targets_each_table():
    for t, (table, col) in st._VECTOR_TABLES.items():
        sql = st.SQL_UPSERT.format(table=table, col=col)
        assert "%s::vector" in sql and f"on conflict ({col}) do update" in sql
        assert sql.count("%s") == 5  # (id, hash, model, vector, updated_at)


def test_knowledge_target_uses_its_own_vector_table():
    assert st._VECTOR_TABLES[st.TARGET_KNOWLEDGE] == ("knowledge_embeddings", "chunk_id")


def test_only_four_tables_touched():
    allsql = " ".join(
        [st.SQL_CLAIM_PENDING, st.SQL_CLAIM_REMOVE, st.SQL_DELETE_JOB, st.SQL_DONE, st.SQL_FAILED, st.SQL_RANK]
        + [s.format(table=t, col=c) for s in (st.SQL_CURRENT, st.SQL_UPSERT, st.SQL_DELETE_VECTOR) for t, c in st._VECTOR_TABLES.values()]
    )
    for banned in (" grants ", "member_grant_profiles", " members "):
        assert banned not in allsql


def test_unknown_target_type_rejected_before_sql():
    s = PgEmbeddingStore("postgresql://invalid")
    with pytest.raises(StoreJobError):
        s.current_vector("OTHER", 1)


def test_connect_failure_hides_connection_string():
    s = PgEmbeddingStore("postgresql://user:secretpw@127.0.0.1:1/nodb")  # 닫힌 포트
    with pytest.raises(StoreUnavailable) as e:
        s.rank(1, [1])
    assert "secretpw" not in str(e.value) and "127.0.0.1" not in str(e.value)


# ── 진짜 PostgreSQL (조건부) ──

PG_URL = os.environ.get("GMPY_TEST_PG_URL", "").strip()


def _pg_skip_reason() -> str | None:
    if not PG_URL:
        return "환경 변수 GMPY_TEST_PG_URL 이 없다(이 PC 의 PostgreSQL 에는 pgvector 가 아직 없다) — 진짜 PostgreSQL 시험 건너뜀"
    try:
        import psycopg

        with psycopg.connect(PG_URL, connect_timeout=5, autocommit=True) as c:
            ok = c.execute("select 1 from pg_available_extensions where name = 'vector'").fetchone()
        if not ok:
            return "GMPY_TEST_PG_URL 서버에 pgvector(vector 확장)가 없다 — 진짜 PostgreSQL 시험 건너뜀"
    except Exception as e:  # noqa: BLE001
        return f"GMPY_TEST_PG_URL 서버에 접속하지 못했다({type(e).__name__}) — 진짜 PostgreSQL 시험 건너뜀"
    return None


_reason = _pg_skip_reason()
pg = pytest.mark.skipif(_reason is not None, reason=_reason or "")

DDL = """
create table embedding_jobs (
    id bigint generated by default as identity primary key, target_type varchar(10) not null, target_id bigint not null,
    text text not null, text_hash char(64) not null, priority smallint not null default 5, status varchar(10) not null default 'PENDING',
    attempts smallint not null default 0, error varchar(500), created_at timestamptz(3) not null default now(), updated_at timestamptz(3) not null default now(),
    constraint embedding_jobs_target_unique unique (target_type, target_id));
create table grant_embeddings (grant_id bigint primary key, text_hash char(64) not null, model varchar(80) not null, embedding vector(384) not null, updated_at timestamptz(3) not null);
create table member_embeddings (member_id bigint primary key, text_hash char(64) not null, model varchar(80) not null, embedding vector(384) not null, updated_at timestamptz(3) not null);
create table knowledge_embeddings (chunk_id bigint primary key, text_hash char(64) not null, model varchar(80) not null, embedding vector(384) not null, updated_at timestamptz(3) not null);
"""


@pytest.fixture()
def pgstore():
    import psycopg

    schema = "gmpytest_" + uuid.uuid4().hex[:10]
    with psycopg.connect(PG_URL, autocommit=True) as c:
        c.execute("create extension if not exists vector")
        c.execute(f"create schema {schema}")
        c.execute(f"set search_path to {schema}, public")
        c.execute(DDL)
    s = PgEmbeddingStore(PG_URL, options=f"-c search_path={schema},public")
    s.schema = schema  # type: ignore[attr-defined]
    yield s
    s.close()
    with psycopg.connect(PG_URL, autocommit=True) as c:
        c.execute(f"drop schema {schema} cascade")


def _exec(s, sql, *params):
    import psycopg

    with psycopg.connect(PG_URL, autocommit=True, options=f"-c search_path={s.schema},public") as c:
        cur = c.execute(sql, params)
        return cur.fetchall() if cur.description else None


def _vec(i, w=1.0):
    v = [0.0] * VECTOR_DIM
    v[i] = w
    return v


@pg
def test_pg_claim_order_and_skip_locked(pgstore):
    for tid, tt, pr in ((1, "GRANT", 5), (2, "GRANT", 5), (7, "MEMBER", 1)):
        _exec(pgstore, "insert into embedding_jobs (target_type, target_id, text, text_hash, priority) values (%s,%s,'글',%s,%s)", tt, tid, "h" * 64, pr)
    jobs = pgstore.claim_pending(10)
    assert [(j.target_type, j.target_id) for j in jobs] == [("MEMBER", 7), ("GRANT", 1), ("GRANT", 2)]  # priority·id 순
    other = PgEmbeddingStore(PG_URL, options=f"-c search_path={pgstore.schema},public")
    try:
        assert other.claim_pending(10) == []  # 잠긴 줄은 건너뛴다(SKIP LOCKED)
    finally:
        other.close()
    pgstore.commit()
    assert len(pgstore.claim_pending(1)) == 1
    pgstore.commit()


@pg
def test_pg_worker_roundtrip_and_rank(pgstore):
    emb = FakeEmbedder()
    _exec(pgstore, "insert into embedding_jobs (target_type, target_id, text, text_hash, priority) values ('MEMBER',1,'소개',%s,1)", "a" * 64)
    _exec(pgstore, "insert into embedding_jobs (target_type, target_id, text, text_hash) values ('GRANT',10,'공고',%s)", "b" * 64)
    w = EmbedWorker(pgstore, emb, Settings())
    r = w.run_batch()
    assert r.done == 2
    assert _exec(pgstore, "select status from embedding_jobs order by id") == [("DONE",), ("DONE",)]
    assert pgstore.current_vector("GRANT", 10) == ("b" * 64, "fake-model")
    rows = pgstore.rank(1, [10, 999])
    assert [g for g, _ in rows] == [10] and rows[0][1] == pytest.approx(1.0, abs=1e-5)  # 같은 가짜 벡터 → 유사도 1
    assert pgstore.rank(2, [10]) == []  # 소개 벡터 없는 회원
    # REMOVE
    _exec(pgstore, "update embedding_jobs set status='REMOVE' where target_type='GRANT'")
    assert w.run_batch().removed == 1
    assert pgstore.current_vector("GRANT", 10) is None and _exec(pgstore, "select count(*) from embedding_jobs") == [(1,)]


@pg
def test_pg_failure_marks(pgstore):
    _exec(pgstore, "insert into embedding_jobs (target_type, target_id, text, text_hash) values ('GRANT',1,'글',%s)", "c" * 64)
    j = pgstore.claim_pending(1)[0]
    pgstore.mark_failed(j.id, 1, "x" * 900, False)
    pgstore.commit()
    assert _exec(pgstore, "select status, attempts, length(error) from embedding_jobs") == [("PENDING", 1, 500)]
    pgstore.claim_pending(1)
    pgstore.mark_failed(j.id, 3, "e", True)
    pgstore.commit()
    assert _exec(pgstore, "select status from embedding_jobs") == [("FAILED",)]


@pg
def test_pg_upsert_dimension_error_is_job_error(pgstore):
    with pytest.raises(StoreJobError):
        pgstore.upsert_vector("GRANT", 1, "d" * 64, "m", [0.1, 0.2])  # 384 가 아님
    pgstore.upsert_vector("GRANT", 1, "d" * 64, "m", _vec(0))  # savepoint 덕에 트랜잭션은 살아 있다
    pgstore.commit()
    assert pgstore.current_vector("GRANT", 1) == ("d" * 64, "m")
    assert vector_literal(_vec(0)).startswith("[1.0,0.0")
